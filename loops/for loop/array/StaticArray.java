public class StaticArray{
    public static void main(String[] args){
    // array creation
    int a[] = new int[5];
    a[0] = 10;
    a[1] = 20;
    a[2] = 30;
    a[3] = 40;
    a[4] = 50;
        
    System.out.println("Static array printed");
    for(int i=0;i<5;i++){
        System.out.println(a[i]);
    }
    }
}
    